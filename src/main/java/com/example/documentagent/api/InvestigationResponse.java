package com.example.documentagent.api;

import com.example.documentagent.domain.Investigation;
import com.example.documentagent.domain.InvestigationStatus;
import java.time.Instant;
import java.util.List;

public record InvestigationResponse(
    Long id,
    String question,
    InvestigationStatus status,
    String conclusion,
    String clarificationQuestion,
    Instant createdAt,
    Instant completedAt,
    List<InvestigationEvidenceResponse> evidence,
    String aiMode,
    String limitation,
    String recommendedNextAction
) {
    public static InvestigationResponse from(Investigation investigation,
                                              List<InvestigationEvidenceResponse> evidence,
                                              String aiMode) {
        String mode = aiMode == null ? "unknown" : aiMode;
        String limitation = "ollama".equalsIgnoreCase(mode)
            ? "Generated by a local LLM using retrieved evidence. Citation validation checks source IDs, but does not guarantee every statement is correct. Retrieval is keyword-based."
            : "Deterministic mock rules only; this response is not generated by a real LLM. Relevance scores are ranking signals, not probabilities.";
        return new InvestigationResponse(
            investigation.getId(), investigation.getQuestion(), investigation.getStatus(),
            investigation.getConclusion(), investigation.getClarificationQuestion(),
            investigation.getCreatedAt(), investigation.getCompletedAt(), evidence,
            mode, limitation, nextAction(investigation.getStatus())
        );
    }

    private static String nextAction(InvestigationStatus status) {
        if (status == null) return "Review the investigation status and retry if necessary.";
        return switch (status) {
            case COMPLETED -> "Review the cited excerpts against the original documents before relying on the conclusion.";
            case INSUFFICIENT_EVIDENCE -> "Upload additional relevant documents or ask a more specific question using terms from the source.";
            case CLARIFICATION_REQUIRED -> "Clarify the policy, date, entity, or scope you want investigated, then submit the question again.";
            case CONFLICTING_EVIDENCE -> "Confirm which source is authoritative and current before taking action.";
            case FAILED -> "Check the application and AI-provider availability, then retry the investigation.";
            case PENDING, IN_PROGRESS -> "Wait for processing to finish, then review the conclusion and source evidence.";
        };
    }

    /** Backward-compatible factory for callers that do not supply the active AI mode. */
    public static InvestigationResponse from(Investigation investigation,
                                              List<InvestigationEvidenceResponse> evidence) {
        return from(investigation, evidence, "mock");
    }
}
